export function domainLabel(value: string | null | undefined): string {
  return value == null ? "Sin dato" : (domainLabels[value] ?? "Sin traducción disponible");
}
export type DomainTone =
  "success" | "warning" | "danger" | "info" | "unknown" | "blocked" | "neutral";
export function domainStatus(value: string): {
  label: string;
  tone: DomainTone;
  icon: "check" | "warning" | "stop" | "clock" | "info";
} {
  const success = [
    "VALID",
    "VERIFIED",
    "COMPLETE",
    "COMPLETED",
    "SUCCEEDED",
    "APPLIED",
    "APPROVED",
    "PAID",
    "DONE",
  ];
  const danger = ["INVALID", "FAILED", "FAIL", "REJECTED", "apply_failed", "error"];
  const blocked = ["BLOCKED", "BLOCKED_MISSING_AUTHORITY", "MANUFACTURING_INCOMPLETE"];
  const waiting = ["PENDING", "QUEUED", "RUNNING", "IN_PROGRESS", "SCHEDULED", "YELLOW"];
  return {
    label: domainLabel(value),
    tone: success.includes(value)
      ? "success"
      : danger.includes(value)
        ? "danger"
        : blocked.includes(value)
          ? "blocked"
          : waiting.includes(value)
            ? "warning"
            : "neutral",
    icon: success.includes(value)
      ? "check"
      : danger.includes(value)
        ? "stop"
        : blocked.includes(value)
          ? "warning"
          : waiting.includes(value)
            ? "clock"
            : "info",
  };
}
