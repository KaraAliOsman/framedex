BEGIN;
CREATE EXTENSION IF NOT EXISTS pgtap;
SET LOCAL search_path=public,private,auth,extensions,pg_temp;
SELECT plan(16);
SELECT has_table('public','catalog_thermal_authorities','thermal sources exist');
SELECT has_table('public','project_thermal_inputs','human envelope inputs exist');
SELECT col_type_is('public','catalog_thermal_authorities','uf','numeric','Uf is exact numeric');
SELECT col_type_is('public','catalog_thermal_authorities','psi_g','numeric','Psi is exact numeric');
SELECT ok(NOT has_table_privilege('authenticated','public.catalog_thermal_authorities','INSERT'),'members cannot forge sources');
SELECT ok(NOT has_table_privilege('authenticated','public.catalog_thermal_authorities','UPDATE'),'members cannot stamp review');
SELECT ok(NOT has_table_privilege('authenticated','public.catalog_thermal_authorities','DELETE'),'sources cannot be deleted');
SELECT ok(NOT has_table_privilege('authenticated','public.project_thermal_inputs','INSERT'),'human inputs use backend authority');
SELECT ok(NOT has_table_privilege('authenticated','public.project_thermal_inputs','UPDATE'),'sealed human input cannot be edited directly');
SELECT ok(NOT has_table_privilege('anon','public.catalog_thermal_authorities','SELECT'),'private certificates have no public read');
SELECT ok(NOT has_table_privilege('anon','public.project_thermal_inputs','SELECT'),'envelope context has no public read');
SELECT ok((SELECT relrowsecurity FROM pg_class WHERE oid='public.catalog_thermal_authorities'::regclass),'source RLS enabled');
SELECT ok((SELECT relrowsecurity FROM pg_class WHERE oid='public.project_thermal_inputs'::regclass),'input RLS enabled');
SELECT has_trigger('public','catalog_thermal_authorities','guard_thermal_report','immutable report guard exists');
SELECT has_trigger('public','project_thermal_inputs','guard_thermal_input','sealed input guard exists');
SELECT ok(NOT has_function_privilege('authenticated','private.guard_thermal_input()','EXECUTE'),'members cannot invoke the definer guard');
SELECT * FROM finish();
ROLLBACK;
